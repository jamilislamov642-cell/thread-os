void isr_handler(registers_t *regs) {
    vga_set_color(VGA_COLOR_LIGHT_RED, VGA_COLOR_BLACK);
    vga_printf("\n*** CPU EXCEPTION %d: %s ***\n", regs->int_no,
               regs->int_no < 32 ? exception_names[regs->int_no] : "Unknown");
    vga_printf("  EIP=0x%x  CS=0x%x  EFLAGS=0x%x  ERR=0x%x\n",
               regs->eip, regs->cs, regs->eflags, regs->err_code);
    vga_printf("  EAX=0x%x  EBX=0x%x  ECX=0x%x  EDX=0x%x\n",
               regs->eax, regs->ebx, regs->ecx, regs->edx);
    vga_printf("  ESP=0x%x  EBP=0x%x  ESI=0x%x  EDI=0x%x\n",
               regs->esp, regs->ebp, regs->esi, regs->edi);
    vga_printf("System halted.\n");
    cli();
    for (;;) hlt();
}

void irq_handler(registers_t *regs) {
    if (interrupt_handlers[regs->int_no]) {
        interrupt_handlers[regs->int_no](regs);
    }
    pic_send_eoi(regs->int_no - IRQ0);
}
