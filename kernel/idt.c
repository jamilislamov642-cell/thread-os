void idt_set_gate(uint8_t num, uint32_t base, uint16_t sel, uint8_t flags) {
    idt[num].base_low  = base & 0xFFFF;
    idt[num].base_high = (base >> 16) & 0xFFFF;
    idt[num].sel       = sel;
    idt[num].always0   = 0;
    idt[num].flags     = flags;
}

static void pic_remap(void) {
    uint8_t a1 = inb(0x21);
    uint8_t a2 = inb(0xA1);
    (void)a1; (void)a2;

    outb(0x20, 0x11); io_wait();
    outb(0xA0, 0x11); io_wait();
    outb(0x21, 0x20); io_wait(); // Master PIC offset 0x20 (32)
    outb(0xA1, 0x28); io_wait(); // Slave PIC offset 0x28 (40)
    outb(0x21, 0x04); io_wait(); // Master: slave at IRQ2
    outb(0xA1, 0x02); io_wait(); // Slave: cascade identity 2
    outb(0x21, 0x01); io_wait(); // 8086 mode
    outb(0xA1, 0x01); io_wait();

    // Mask all IRQs initially
    outb(0x21, 0xFF);
    outb(0xA1, 0xFF);
}

